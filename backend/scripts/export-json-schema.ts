/**
 * Writes docs/ielts-package.schema.json (JSON Schema draft 2020-12) from the
 * zod schema, for the AI generator (structured output / validation).
 *   npm run schema:export
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { z } from 'zod';
import { ieltsPackageSchema, PACKAGE_SCHEMA_VERSION } from '../src/ielts-format/package.schema';

const schema = z.toJSONSchema(ieltsPackageSchema, { io: 'input', unrepresentable: 'any' });
const out = {
  $id: `https://ielts.eduportal.az/schema/ielts-package-${PACKAGE_SCHEMA_VERSION}.json`,
  title: 'IELTS Test Package',
  description:
    'One complete IELTS mock test generated by AI. Structural rules beyond this schema (numbering 1-40, gaps, answer keys, asset types) are checked by buildIeltsExam(); see docs/IELTS_PACKAGE_FORMAT.md.',
  ...schema,
};
const path = join(__dirname, '..', '..', 'docs', 'ielts-package.schema.json');
writeFileSync(path, JSON.stringify(out, null, 2) + '\n');
console.log(`wrote ${path}`);
