/**
 * IELTS Test Package — the JSON standard the AI generator must produce
 * (docs/IELTS_PACKAGE_FORMAT.md, JSON Schema: docs/ielts-package.schema.json).
 *
 * One package = one complete IELTS mock test: Listening (4 parts, 40 questions),
 * Reading (3 sections, 40 questions), Writing (Task 1 + Task 2) and
 * Speaking (Parts 1–3). The structural rules that zod can not express
 * (numbering, gaps, asset references, per-module allowed question types…)
 * are checked by buildIeltsExam() in build-exam.ts.
 *
 * Pure module: no Nest, no I/O. Safe to import from scripts and tests.
 */
import { z } from 'zod';

export const PACKAGE_SCHEMA_VERSION = '1.0';

// ---------------------------------------------------------------- primitives

/** Package-local identifier (assets, texts). */
export const localId = z
  .string()
  .regex(/^[A-Za-z0-9][A-Za-z0-9_-]{0,63}$/, 'use 1-64 characters: letters, digits, "_" or "-"');

/**
 * Plain text. Newlines separate paragraphs; **double asterisks** mark bold
 * (IELTS prints word limits in bold). No HTML: it is always rendered as text.
 */
const text = (max: number) => z.string().trim().min(1).max(max);

/** 1..40 — IELTS numbers Listening and Reading questions 1-40. */
const questionNumber = z.number().int().min(1).max(40);

/** A, B, C … (multiple choice, matching, map letters, word bank). */
const letterKey = z.string().regex(/^[A-Z]$/, 'option keys are single capital letters A-Z');
/** i, ii, iii … (matching headings). */
const romanKey = z
  .string()
  .regex(/^(i|ii|iii|iv|v|vi|vii|viii|ix|x|xi|xii|xiii|xiv|xv)$/, 'heading keys are lower-case roman numerals i-xv');
/** Paragraph label printed in the passage: A, B, C … */
const paragraphLabel = letterKey;

const option = z.object({ key: letterKey, text: text(400) });
const headingOption = z.object({ key: romanKey, text: text(200) });

/**
 * Word limit of a typed answer, exactly as IELTS words it:
 *   {maxWords:1, allowNumber:false} → "ONE WORD ONLY"
 *   {maxWords:2, allowNumber:true}  → "NO MORE THAN TWO WORDS AND/OR A NUMBER"
 *   {maxWords:0, allowNumber:true}  → "A NUMBER"
 */
export const wordLimitSchema = z
  .object({
    maxWords: z.number().int().min(0).max(5),
    allowNumber: z.boolean(),
  })
  .refine((w) => w.maxWords > 0 || w.allowNumber, 'a word limit must allow at least one word or a number');

/**
 * Accepted spellings of a typed answer. Words in round brackets are optional:
 * "(the) library" accepts "the library" and "library". Matching ignores case,
 * extra spaces and a trailing full stop (answer-text.ts).
 */
const acceptedAnswers = z.array(text(80)).min(1).max(10);

/** Optional worked example printed above a question group (IELTS "Example"). */
const example = text(500).optional();

/** Common fields of every question group. */
const groupBase = {
  /** Overrides the standard IELTS instruction generated by the builder. */
  instructions: text(1200).optional(),
  /** Heading printed above the task, e.g. "Hotel booking form", "List of Headings". */
  title: text(200).optional(),
  example,
};

// ---------------------------------------------------------------- question groups

/** Choose ONE letter. Listening + Reading. */
const multipleChoice = z.object({
  type: z.literal('multiple_choice'),
  ...groupBase,
  questions: z
    .array(
      z.object({
        number: questionNumber,
        stem: text(600),
        options: z.array(option).min(3).max(7),
        answer: letterKey,
      }),
    )
    .min(1),
});

/** "Choose TWO / THREE letters, A–E." One item spans as many numbers as answers. */
const multipleChoiceMulti = z.object({
  type: z.literal('multiple_choice_multi'),
  ...groupBase,
  items: z
    .array(
      z.object({
        numbers: z.array(questionNumber).min(2).max(3),
        stem: text(600),
        options: z.array(option).min(4).max(8),
        answers: z.array(letterKey).min(2).max(3),
      }),
    )
    .min(1),
});

/** Identifying information. Reading only. */
const trueFalseNotGiven = z.object({
  type: z.literal('true_false_not_given'),
  ...groupBase,
  questions: z
    .array(z.object({ number: questionNumber, statement: text(600), answer: z.enum(['TRUE', 'FALSE', 'NOT_GIVEN']) }))
    .min(1),
});

/** Identifying the writer's views / claims. Reading only. */
const yesNoNotGiven = z.object({
  type: z.literal('yes_no_not_given'),
  ...groupBase,
  questions: z
    .array(z.object({ number: questionNumber, statement: text(600), answer: z.enum(['YES', 'NO', 'NOT_GIVEN']) }))
    .min(1),
});

/** Choose the heading of each paragraph. Reading only. */
const matchingHeadings = z.object({
  type: z.literal('matching_headings'),
  ...groupBase,
  /** Which text of the section the paragraphs belong to (default 0). */
  textIndex: z.number().int().min(0).max(3).default(0),
  headings: z.array(headingOption).min(3).max(15),
  questions: z.array(z.object({ number: questionNumber, paragraph: paragraphLabel, answer: romanKey })).min(1),
});

/** "Which paragraph contains the following information?" Reading only. */
const matchingInformation = z.object({
  type: z.literal('matching_information'),
  ...groupBase,
  textIndex: z.number().int().min(0).max(3).default(0),
  /** IELTS prints "NB You may use any letter more than once." */
  allowReuse: z.boolean().default(true),
  questions: z.array(z.object({ number: questionNumber, statement: text(600), answer: paragraphLabel })).min(1),
});

/**
 * Match statements to a list (people, places, dates, features…).
 * Reading "matching features" and the Listening "matching" task.
 */
const matchingFeatures = z.object({
  type: z.literal('matching_features'),
  ...groupBase,
  /** Title of the option box, e.g. "List of Researchers". */
  optionsTitle: text(120).optional(),
  options: z.array(option).min(3).max(12),
  allowReuse: z.boolean().default(false),
  questions: z.array(z.object({ number: questionNumber, statement: text(600), answer: letterKey })).min(1),
});

/** Complete each sentence with the correct ending. Reading only. */
const matchingSentenceEndings = z.object({
  type: z.literal('matching_sentence_endings'),
  ...groupBase,
  endings: z.array(option).min(3).max(12),
  questions: z.array(z.object({ number: questionNumber, sentenceStart: text(400), answer: letterKey })).min(1),
});

/** Plan / map / diagram labelling with letters printed on the picture. Listening only. */
const mapLabelling = z.object({
  type: z.literal('map_labelling'),
  ...groupBase,
  image: localId,
  /** Letters printed on the image, e.g. A–I. */
  letters: z.array(letterKey).min(3).max(12),
  questions: z.array(z.object({ number: questionNumber, label: text(200), answer: letterKey })).min(1),
});

/** A gap inside a completion task: typed answer (answerMode write) … */
const writeGap = z.object({ number: questionNumber, answers: acceptedAnswers });
/** … or a letter from the word bank (answerMode select). */
const selectGap = z.object({ number: questionNumber, answer: letterKey });

const line = z.object({
  text: text(600),
  style: z.enum(['heading', 'text', 'bullet', 'indent']).default('text'),
});

/**
 * Form / note / table / flow-chart / summary completion. Gaps are written in
 * the content as {{n}} where n is the question number, e.g.
 *   "Name of hotel: {{1}}"   |   table cell "{{7}} per night"
 */
const completion = z
  .object({
    type: z.literal('completion'),
    ...groupBase,
    variant: z.enum(['form', 'note', 'table', 'flow_chart', 'summary']),
    /** write: candidate types words; select: candidate picks from `options` (word bank). */
    answerMode: z.enum(['write', 'select']).default('write'),
    wordLimit: wordLimitSchema.optional(),
    /** Word bank for answerMode "select" (A–L). */
    options: z.array(option).min(3).max(15).optional(),
    /** form, note, summary */
    lines: z.array(line).min(1).max(60).optional(),
    /** table */
    table: z
      .object({
        columns: z.array(z.string().trim().max(120)).min(1).max(6),
        rows: z.array(z.array(z.string().trim().max(400)).min(1).max(6)).min(1).max(15),
      })
      .optional(),
    /** flow_chart: boxes from top to bottom */
    steps: z.array(text(500)).min(2).max(15).optional(),
    gaps: z.array(z.union([writeGap, selectGap])).min(1),
  })
  .superRefine((g, ctx) => {
    const want = g.variant === 'table' ? 'table' : g.variant === 'flow_chart' ? 'steps' : 'lines';
    for (const k of ['lines', 'table', 'steps'] as const) {
      if (k === want && g[k] === undefined) ctx.addIssue({ code: 'custom', path: [k], message: `${g.variant} needs "${k}"` });
      if (k !== want && g[k] !== undefined) ctx.addIssue({ code: 'custom', path: [k], message: `${g.variant} must not have "${k}"` });
    }
    if (g.answerMode === 'write' && !g.wordLimit)
      ctx.addIssue({ code: 'custom', path: ['wordLimit'], message: 'answerMode "write" needs wordLimit' });
    if (g.answerMode === 'select' && !g.options)
      ctx.addIssue({ code: 'custom', path: ['options'], message: 'answerMode "select" needs options (word bank)' });
    g.gaps.forEach((gap, i) => {
      const isWrite = 'answers' in gap;
      if (isWrite !== (g.answerMode === 'write'))
        ctx.addIssue({
          code: 'custom',
          path: ['gaps', i],
          message: g.answerMode === 'write' ? 'gap needs "answers" (typed answers)' : 'gap needs "answer" (a word-bank letter)',
        });
    });
  });

/** Complete each sentence with words from the passage / recording. */
const sentenceCompletion = z.object({
  type: z.literal('sentence_completion'),
  ...groupBase,
  wordLimit: wordLimitSchema,
  /** `sentence` contains exactly one gap {{n}} with its own number. */
  questions: z.array(z.object({ number: questionNumber, sentence: text(600), answers: acceptedAnswers })).min(1),
});

/** Label a diagram by typing words; gaps are positioned on the image (percent). */
const diagramLabelCompletion = z.object({
  type: z.literal('diagram_label_completion'),
  ...groupBase,
  image: localId,
  wordLimit: wordLimitSchema,
  labels: z
    .array(
      z.object({
        number: questionNumber,
        /** Gap position on the image, 0-100 % from the left / top. */
        x: z.number().min(0).max(100),
        y: z.number().min(0).max(100),
        answers: acceptedAnswers,
      }),
    )
    .min(1),
});

/** Short-answer questions. */
const shortAnswer = z.object({
  type: z.literal('short_answer'),
  ...groupBase,
  wordLimit: wordLimitSchema,
  questions: z.array(z.object({ number: questionNumber, question: text(600), answers: acceptedAnswers })).min(1),
});

export const questionGroupSchema = z.discriminatedUnion('type', [
  multipleChoice,
  multipleChoiceMulti,
  trueFalseNotGiven,
  yesNoNotGiven,
  matchingHeadings,
  matchingInformation,
  matchingFeatures,
  matchingSentenceEndings,
  mapLabelling,
  completion,
  sentenceCompletion,
  diagramLabelCompletion,
  shortAnswer,
]);

export type QuestionGroupInput = z.input<typeof questionGroupSchema>;
export type QuestionGroup = z.output<typeof questionGroupSchema>;
export type QuestionType = QuestionGroup['type'];
export type WordLimit = z.output<typeof wordLimitSchema>;

// ---------------------------------------------------------------- assets

export const AUDIO_MIME = ['audio/mpeg', 'audio/wav', 'audio/ogg', 'audio/webm', 'audio/mp4'] as const;
export const IMAGE_MIME = ['image/png', 'image/jpeg', 'image/webp', 'image/svg+xml'] as const;

/**
 * Generated media. Exactly one of `data` (base64, no "data:" prefix) or
 * `url` (https) must be present. URL assets are downloaded once at import,
 * so a test keeps working when the generator's storage expires.
 */
export const assetSchema = z
  .object({
    id: localId,
    kind: z.enum(['audio', 'image']),
    mimeType: z.enum([...AUDIO_MIME, ...IMAGE_MIME]),
    data: z.string().regex(/^[A-Za-z0-9+/=\s]+$/, 'data must be plain base64').optional(),
    url: z.string().url().startsWith('https://', 'asset url must be https').optional(),
    /** Audio length in seconds (Listening timing and resume position). */
    durationSeconds: z.number().positive().max(1800).optional(),
    /** Image description for screen readers / teachers. */
    alt: z.string().trim().max(500).optional(),
  })
  .superRefine((a, ctx) => {
    if ((a.data === undefined) === (a.url === undefined))
      ctx.addIssue({ code: 'custom', path: ['data'], message: 'give exactly one of "data" or "url"' });
    const okMime = a.kind === 'audio' ? (AUDIO_MIME as readonly string[]) : (IMAGE_MIME as readonly string[]);
    if (!okMime.includes(a.mimeType))
      ctx.addIssue({ code: 'custom', path: ['mimeType'], message: `${a.mimeType} is not a valid ${a.kind} type` });
    if (a.kind === 'audio' && a.durationSeconds === undefined)
      ctx.addIssue({ code: 'custom', path: ['durationSeconds'], message: 'audio needs durationSeconds' });
  });
export type AssetInput = z.output<typeof assetSchema>;

// ---------------------------------------------------------------- listening

const listeningPart = z.object({
  partNumber: z.number().int().min(1).max(4),
  /** Who is speaking and where, e.g. "A conversation between a hotel receptionist and a guest". Shown to staff only. */
  context: text(400).optional(),
  /** One recording per part (IELTS plays it ONCE). */
  audio: localId,
  /** Full transcript; staff review only, never sent to candidates. */
  transcript: text(20000),
  questionGroups: z.array(questionGroupSchema).min(1).max(6),
});

// ---------------------------------------------------------------- reading

const readingText = z.object({
  title: text(200),
  subtitle: text(400).optional(),
  /** Paragraphs in order. `label` (A, B, C…) is required by matching headings / information. */
  paragraphs: z
    .array(z.object({ label: paragraphLabel.optional(), text: text(4000) }))
    .min(1)
    .max(20),
  image: localId.optional(),
  imageCaption: text(300).optional(),
});

const readingSection = z.object({
  sectionNumber: z.number().int().min(1).max(3),
  /**
   * Academic: exactly one long passage per section.
   * General Training: section 1 two-three short texts, section 2 two texts,
   * section 3 one long text.
   */
  texts: z.array(readingText).min(1).max(4),
  questionGroups: z.array(questionGroupSchema).min(1).max(6),
});

// ---------------------------------------------------------------- writing

const academicTask1 = z.object({
  kind: z.literal('academic_report'),
  visualType: z.enum(['line_graph', 'bar_chart', 'pie_chart', 'table', 'mixed_charts', 'map', 'process_diagram']),
  /** "The chart below shows …" — the builder appends the standard instruction. */
  prompt: text(1000),
  image: localId,
});

const generalTask1 = z.object({
  kind: z.literal('general_letter'),
  letterType: z.enum(['formal', 'semi_formal', 'informal']),
  /** The situation, e.g. "You recently bought a piece of equipment for your kitchen but it did not work." */
  situation: text(1000),
  /** "In your letter …" bullet points (IELTS always gives three). */
  bulletPoints: z.array(text(300)).length(3),
  /** Opening the candidate must use, e.g. "Dear Sir or Madam," */
  salutation: text(100).optional(),
});

const writingTask2 = z.object({
  essayType: z.enum(['opinion', 'discussion', 'advantages_disadvantages', 'problem_solution', 'two_part_question']),
  /** The topic statement. */
  prompt: text(1500),
  /** The task, e.g. "Discuss both these views and give your own opinion." */
  question: text(500),
});

// ---------------------------------------------------------------- speaking

const spokenQuestion = z.object({
  text: text(400),
  /** Examiner voice for this question (optional; text is shown when absent). */
  audio: localId.optional(),
});

const speaking = z.object({
  part1: z.object({
    topics: z
      .array(z.object({ topic: text(120), questions: z.array(spokenQuestion).min(2).max(6) }))
      .min(2)
      .max(4),
  }),
  part2: z.object({
    /** "Describe a time when you helped someone." */
    topic: text(300),
    /** "You should say:" bullet points. */
    bulletPoints: z.array(text(200)).min(3).max(4),
    /** "and explain how you felt about it." */
    finalPrompt: text(300),
    introAudio: localId.optional(),
    /** One or two rounding-off questions asked after the long turn. */
    roundingOff: z.array(spokenQuestion).max(2).default([]),
  }),
  part3: z.object({
    themes: z
      .array(z.object({ theme: text(120), questions: z.array(spokenQuestion).min(2).max(6) }))
      .min(1)
      .max(3),
  }),
});

// ---------------------------------------------------------------- package

export const ieltsPackageSchema = z.object({
  schemaVersion: z.literal(PACKAGE_SCHEMA_VERSION),
  testType: z.enum(['academic', 'general_training']),
  title: text(200),
  /** Free information about the generation (model, prompt id, target band…). Stored, never shown to candidates. */
  meta: z.record(z.string(), z.unknown()).optional(),
  assets: z.array(assetSchema).max(80),
  listening: z.object({ parts: z.array(listeningPart).length(4) }),
  reading: z.object({ sections: z.array(readingSection).length(3) }),
  writing: z.object({ task1: z.discriminatedUnion('kind', [academicTask1, generalTask1]), task2: writingTask2 }),
  speaking,
});

export type IeltsPackageInput = z.input<typeof ieltsPackageSchema>;
export type IeltsPackage = z.output<typeof ieltsPackageSchema>;
export type ListeningPart = IeltsPackage['listening']['parts'][number];
export type ReadingSection = IeltsPackage['reading']['sections'][number];
export type ReadingText = ReadingSection['texts'][number];
export type WritingTask1 = IeltsPackage['writing']['task1'];
export type SpeakingPackage = IeltsPackage['speaking'];
